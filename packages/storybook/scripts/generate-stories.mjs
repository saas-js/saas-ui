// Generates Storybook stories from the docs examples.
//
// Every `<ExampleTabs name="…" />` in the saas-ui docs becomes a story, grouped
// by the docs page that renders it. Story ids follow the docs URL, so the
// `links.storybook` frontmatter (e.g. `components-button--basic`) resolves:
//
//   docs/(core)/components/(buttons)/button.mdx + button-basic.tsx
//   → title "Components/Button", export `Basic` → id components-button--basic
//
// Run with `pnpm generate`; `build` runs it first. Output is gitignored.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const docsDir = path.resolve(root, '../../apps/website/content/saas-ui/docs')
const examplesDir = path.resolve(root, '../../apps/compositions/src/examples')
const outDir = path.join(root, 'stories/generated')

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) return walk(full)
    return entry.name.endsWith('.mdx') ? [full] : []
  })

const pascal = (s) =>
  s
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('')

const startCase = (s) =>
  s
    .split('-')
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join(' ')

const exampleExport = (name) => {
  const file = path.join(examplesDir, `${name}.tsx`)
  if (!fs.existsSync(file)) return null
  const source = fs.readFileSync(file, 'utf8')
  const expected = pascal(name)
  if (new RegExp(`export (const|function) ${expected}\\b`).test(source)) {
    return expected
  }
  // A few examples don't follow the filename convention; take the first export.
  const match = source.match(/export (?:const|function) ([A-Z]\w*)/)
  return match?.[1] ?? null
}

fs.rmSync(outDir, { recursive: true, force: true })
fs.mkdirSync(outDir, { recursive: true })

let pages = 0
let stories = 0
const missing = []
const storyIds = new Set()
const docLinks = []

// Mirrors Storybook's id sanitizer for our kebab-case titles and names.
const toId = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')

for (const file of walk(docsDir)) {
  const source = fs.readFileSync(file, 'utf8')
  const names = [
    ...new Set(
      [...source.matchAll(/<ExampleTabs[^>]*\bname="([^"]+)"/g)].map(
        (m) => m[1],
      ),
    ),
  ]
  const link = source.match(/^\s+storybook:\s*(\S+)/m)?.[1]
  if (link) docLinks.push([path.relative(docsDir, file), link])
  if (names.length === 0) continue

  // URL segments without route groups: components/button, charts/bar, ...
  const segments = path
    .relative(docsDir, file)
    .replace(/\.mdx$/, '')
    .split(path.sep)
    .filter((s) => !/^\(.*\)$/.test(s) && s !== 'index')
  const slug = segments.at(-1)
  const title = segments.map(startCase).join('/')

  const imports = []
  const exports = []
  const used = new Set()

  for (const name of names) {
    const component = exampleExport(name)
    if (!component) {
      missing.push(`${title}: ${name}`)
      continue
    }

    let storyName = name.startsWith(`${slug}-`)
      ? name.slice(slug.length + 1)
      : name
    let exportName = pascal(storyName)
    if (/^\d/.test(exportName)) exportName = `Story${exportName}`
    while (used.has(exportName)) exportName += 'X'
    used.add(exportName)
    storyIds.add(`${toId(title)}--${toId(startCase(storyName))}`)

    const local = `Example${imports.length}`
    imports.push(
      `import { ${component} as ${local} } from 'compositions/examples/${name}'`,
    )
    exports.push(
      `export const ${exportName}: Story = {\n  name: ${JSON.stringify(startCase(storyName))},\n  render: () => <${local} />,\n}`,
    )
  }

  if (exports.length === 0) continue

  const out = [
    '// Generated by scripts/generate-stories.mjs. Do not edit.',
    "import type { Meta, StoryObj } from '@storybook/react-vite'",
    ...imports,
    '',
    `const meta: Meta = { title: ${JSON.stringify(title)} }`,
    'export default meta',
    'type Story = StoryObj',
    '',
    exports.join('\n\n'),
    '',
  ].join('\n')

  fs.writeFileSync(
    path.join(outDir, `${segments.join('-')}.stories.tsx`),
    out,
  )
  pages++
  stories += exports.length
}

console.log(`Generated ${stories} stories across ${pages} docs pages.`)
const brokenLinks = docLinks.filter(([, id]) => !storyIds.has(id))
if (brokenLinks.length) {
  console.warn(`${brokenLinks.length} docs pages link to a story that doesn't exist:`)
  for (const [file, id] of brokenLinks) console.warn(`  ${file}: ${id}`)
}
if (missing.length) {
  console.warn(`Skipped ${missing.length} ExampleTabs with no example file:`)
  for (const m of missing) console.warn(`  ${m}`)
}
